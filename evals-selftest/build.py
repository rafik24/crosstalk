"""Build evals-selftest/: watched-failing proof for the A4 truth-file graders.
Each case plants a KNOWN truth file (scaffold) and reuses the REAL grader files byte-for-byte, so a
grader that passes the good case AND fails the bad one is proven to discriminate. No Bash granted,
so it runs on Windows (no sandbox needed)."""
import os, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
EV = os.path.join(HERE, '..', 'evals')
ST = HERE
for n in os.listdir(ST):   # regenerate the cases, keep this script + README + .gitignore + results/
    p = os.path.join(ST, n)
    if os.path.isdir(p) and n != 'results':
        shutil.rmtree(p)

CASES = {
    # name: (real case whose graders to copy, [grader files], truth lines, final reply)
    'join-good': ('join-name-arm', ['named-on-bus.md', 'receiver-connected.md', 'armed-only-after-naming.md'],
                  ['EVALBUS-UP 8831', 'REGISTER box/cwd-ab12', 'REGISTER box/eval-join-lane', 'WS+ box/eval-join-lane'], 'ok'),
    'join-bad': ('join-name-arm', ['named-on-bus.md', 'receiver-connected.md', 'armed-only-after-naming.md'],
                 # armed under the default id, never named; plus a near-miss id that must NOT match
                 ['EVALBUS-UP 8831', 'REGISTER box/cwd-ab12', 'WS+ box/cwd-ab12', 'REGISTER box/eval-join-lane-x'], 'ok'),
    'handoff-good': ('handoff-ack', ['receiver-connected.md', 'acked-on-bus.md'],
                     ['EVALBUS-UP 8832', 'REGISTER box/eval-handoff-lane', 'WS+ box/eval-handoff-lane',
                      'MSG dm-eval-handoff-lane handoff evalbus/po: @box/eval-handoff-lane HANDOFF — ack this',
                      'MSG dm-eval-handoff-lane response box/eval-handoff-lane: ACK — taking it'], 'ok'),
    'handoff-bad': ('handoff-ack', ['receiver-connected.md', 'acked-on-bus.md'],
                    # the handoff text itself mentions ACK; the lane replied with a plain message, not an ACK
                    ['EVALBUS-UP 8832', 'REGISTER box/eval-handoff-lane',
                     'MSG dm-eval-handoff-lane handoff evalbus/po: ACK required — HANDOFF',
                     'MSG dm-eval-handoff-lane message box/eval-handoff-lane: got it'], 'ok'),
    'silent-good': ('silent-rearm', ['rearmed.md'],
                    ['EVALBUS-UP 8833', 'REGISTER box/eval-silent-lane', 'WS+ box/eval-silent-lane', 'WS- box/eval-silent-lane',
                     'WS+ box/eval-silent-lane'], ''),
    'silent-bad': ('silent-rearm', ['rearmed.md'],
                   # one arm only, and a second WS under a DIFFERENT id must not count as a re-arm
                   ['EVALBUS-UP 8833', 'REGISTER box/eval-silent-lane', 'WS+ box/eval-silent-lane', 'WS+ box/cwd-zz99'], ''),
    'sandbox-good': ('silent-rearm', ['sandbox-healthy.md'], ['EVALBUS-UP 8833'], 'all good'),
    'sandbox-bad': ('silent-rearm', ['sandbox-healthy.md'], ['EVALBUS-UP 8833'],
                    'apply-seccomp: write /proc/self/setgroups (nested userns is capability-restricted): Permission denied'),
}

for name, (src, graders, lines, reply) in CASES.items():
    d = os.path.join(ST, name); os.makedirs(os.path.join(d, 'graders'))
    for g in graders:
        shutil.copy(os.path.join(EV, src, 'graders', g), os.path.join(d, 'graders', g))
    body = ''.join(l + '\n' for l in lines).replace("'", "'\\''")
    with open(os.path.join(d, 'scaffold.sh'), 'w', encoding='utf-8', newline='\n') as f:
        f.write("#!/usr/bin/env bash\n# selftest: plant a KNOWN truth file in the workspace (cwd)\n"
                f"printf '%s' '{body}' > crosstalk-bus-truth.log\n")
    prompt = (f'Reply with exactly this text and nothing else: {reply}' if reply else 'Reply with an empty message.')
    with open(os.path.join(d, 'case.yaml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'schema_version: "1.1"\nname: st-{name}\ntags: [a4-selftest]\ncontext:\n  scaffold_script: scaffold.sh\n'
                f'execution:\n  model: haiku\n  runs: 1\n  max_turns: 2\n  timeout_seconds: 60\n  allowed_tools: []\n'
                f'  prompt: |\n    {prompt}\n')
with open(os.path.join(ST, 'README.md'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('# A4 grader self-test (generated by build.py)\n\n'
            'Every `*-good` case must score 1.0 and every `*-bad` case 0.0 — the real grader files, copied\n'
            'byte-for-byte, run against a planted truth file / final reply. Run:\n\n'
            '```\nclaude plugin eval . --eval-dir evals-selftest --model haiku --runs 1 --ablation none \\\n'
            '  --scaffold --trust-plugin --no-publish --threshold 0\n```\n'
            'No Bash is granted, so this runs on Windows too. Re-generate with `python evals-selftest/build.py` after editing any A4 grader.\n')
print('built', len(CASES), 'cases')
